/**
 * Runs both SQL scenarios against the seeded in-memory database, prints the results, and writes
 * evidence to reports/sql/: a markdown summary plus PNG screenshots (schema, query and output)
 * rendered with Playwright.
 *
 *   npm run sql
 */
import fs from 'fs';
import path from 'path';
import { chromium } from 'playwright';
import { openSeededDb, QueryName, QUERIES, querySql, runQuery, SQL_DIR } from './db';

const OUT = path.resolve(__dirname, '../reports/sql');
const escape = (s: unknown) => String(s ?? 'NULL').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function htmlPage(title: string, sections: { heading: string; sql?: string; table?: { columns: string[]; rows: Record<string, unknown>[] } }[]) {
  const css = `body{font:14px/1.45 system-ui,Segoe UI,sans-serif;margin:24px;color:#1f2328;background:#fff}
    h1{font-size:20px;margin:0 0 4px} h2{font-size:15px;margin:22px 0 8px;color:#0b5394}
    .meta{color:#57606a;font-size:12px;margin-bottom:12px}
    pre{background:#f6f8fa;border:1px solid #d0d7de;border-radius:6px;padding:12px;font:12px/1.4 Consolas,monospace;white-space:pre-wrap}
    table{border-collapse:collapse;font-size:12.5px} th,td{border:1px solid #d0d7de;padding:5px 9px;text-align:left}
    th{background:#eaeef2} tr:nth-child(even) td{background:#f6f8fa} .count{color:#57606a;font-size:12px;margin-top:6px}`;
  const body = sections
    .map(
      (s) =>
        `<h2>${escape(s.heading)}</h2>` +
        (s.sql ? `<pre>${escape(s.sql.trim())}</pre>` : '') +
        (s.table
          ? `<table><thead><tr>${s.table.columns.map((c) => `<th>${escape(c)}</th>`).join('')}</tr></thead><tbody>${s.table.rows
              .map((r) => `<tr>${s.table!.columns.map((c) => `<td>${escape(r[c])}</td>`).join('')}</tr>`)
              .join('')}</tbody></table><div class="count">${s.table.rows.length} row(s)</div>`
          : ''),
    )
    .join('');
  return `<!doctype html><html><head><meta charset="utf-8"><title>${escape(title)}</title><style>${css}</style></head><body><h1>${escape(title)}</h1><div class="meta">SQLite (sql.js) · generated ${new Date().toISOString()}</div>${body}</body></html>`;
}

function markdownTable({ columns, rows }: { columns: string[]; rows: Record<string, unknown>[] }) {
  return [`| ${columns.join(' | ')} |`, `|${columns.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${columns.map((c) => String(r[c] ?? 'NULL')).join(' | ')} |`)].join('\n');
}

async function main() {
  fs.mkdirSync(path.join(OUT, 'screenshots'), { recursive: true });
  const db = await openSeededDb();
  const schema = fs.readFileSync(path.join(SQL_DIR, 'schema.sql'), 'utf8');

  const pages: { file: string; html: string }[] = [];
  const md: string[] = ['# SQL results', '', `Generated by \`npm run sql\` on ${new Date().toISOString()} (SQLite via sql.js).`, ''];

  const tableCounts = runQueryRaw(db, `SELECT 'transactions' AS table_name, COUNT(*) AS row_count FROM transactions UNION ALL SELECT 'matches', COUNT(*) FROM matches UNION ALL SELECT 'batting_scores', COUNT(*) FROM batting_scores UNION ALL SELECT 'players', COUNT(*) FROM players`);
  pages.push({ file: 'schema.png', html: htmlPage('Schema', [{ heading: 'schema.sql', sql: schema }, { heading: 'Seeded row counts', table: tableCounts }]) });

  for (const [i, name] of (Object.keys(QUERIES) as QueryName[]).entries()) {
    const result = runQuery(db, name);
    const title = `Scenario ${i + 1} — ${name}`;
    console.log(`\n=== ${title} (${result.rows.length} rows) ===`);
    console.table(result.rows);

    const inputs =
      name === 'round-trip transfers'
        ? runQueryRaw(db, 'SELECT * FROM transactions ORDER BY txn_time')
        : runQueryRaw(db, `SELECT p.player_name, m.season, m.match_date, s.match_id, s.runs FROM batting_scores s JOIN matches m USING (match_id) JOIN players p USING (player_id) ORDER BY p.player_name, m.match_date`);

    pages.push({
      file: `scenario${i + 1}.png`,
      html: htmlPage(title, [
        { heading: QUERIES[name], sql: querySql(name) },
        { heading: 'Output', table: result },
      ]),
    });
    pages.push({ file: `scenario${i + 1}-input-data.png`, html: htmlPage(`${title} — input data`, [{ heading: 'Seeded rows', table: inputs }]) });
    md.push(`## ${title}`, '', `Query: [\`sql/${QUERIES[name]}\`](../../sql/${QUERIES[name]})`, '', markdownTable(result), '', `![${title}](screenshots/scenario${i + 1}.png)`, '');
  }

  fs.writeFileSync(path.join(OUT, 'results.md'), md.join('\n'));

  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
  for (const p of pages) {
    await page.setContent(p.html);
    await page.screenshot({ path: path.join(OUT, 'screenshots', p.file), fullPage: true });
  }
  await browser.close();
  console.log(`\nEvidence written to ${path.relative(process.cwd(), OUT)}`);
}

function runQueryRaw(db: Awaited<ReturnType<typeof openSeededDb>>, sql: string) {
  const [r] = db.exec(sql);
  return { columns: r.columns, rows: r.values.map((v) => Object.fromEntries(r.columns.map((c, i) => [c, v[i]]))) };
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
