/**
 * Runs every suite, captures each one's console output to reports/<suite>/console.log, and writes
 * reports/SUMMARY.md. Unlike `npm test` it keeps going after a failing suite, because the
 * broken-locator run is *expected* to fail and its output is part of the evidence.
 *
 *   npm run evidence
 */
import { spawnSync } from 'child_process';
import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(__dirname, '..');
const REPORTS = path.join(ROOT, 'reports');

interface Suite {
  name: string;
  script: string;
  logDir: string;
  expectFailure?: boolean;
  description: string;
}

const suites: Suite[] = [
  { name: 'API (B1/B2)', script: 'test:api', logDir: 'api', description: 'Catalogue API — happy paths, validation, edge cases' },
  { name: 'SQL (B4)', script: 'test:sql', logDir: 'sql', description: 'Round-trip transfers and IPL streak queries' },
  { name: 'UI (B3)', script: 'test:ui', logDir: 'ui', description: 'emicalculator.net pie and bar chart test cases' },
  { name: 'Broken locators, healing OFF', script: 'test:broken', logDir: 'self-healing/broken-run', expectFailure: true, description: 'Deliberately broken locators fail and are detected' },
  { name: 'Broken locators, healing ON', script: 'test:healing', logDir: 'self-healing/healed-run', description: 'Healer proposes, validates and uses replacements' },
];

const strip = (s: string) => s.replace(/\x1b\[[0-9;]*m/g, '');
const rows: string[] = [];

for (const suite of suites) {
  console.log(`\n▶ ${suite.name}  (npm run ${suite.script})`);
  const started = Date.now();
  const run = spawnSync('npm', ['run', suite.script], { cwd: ROOT, encoding: 'utf8', shell: true, env: { ...process.env, FORCE_COLOR: '0' } });
  const output = strip(`${run.stdout ?? ''}${run.stderr ?? ''}`);
  const dir = path.join(REPORTS, suite.logDir);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'console.log'), output);

  const scenarios = output.match(/^\d+ scenarios? \(.*\)$/m)?.[0] ?? 'n/a';
  const steps = output.match(/^\d+ steps? \(.*\)$/m)?.[0] ?? 'n/a';
  const passed = run.status === 0;
  const verdict = passed ? '✅ passed' : suite.expectFailure ? '⚠️ failed (expected)' : '❌ failed';
  console.log(`  ${verdict} — ${scenarios}; ${steps} — ${((Date.now() - started) / 1000).toFixed(1)}s`);
  rows.push(
    `| ${suite.name} | \`npm run ${suite.script}\` | ${verdict} | ${scenarios} | ${steps} | [HTML](${suite.logDir}/cucumber-report.html) · [console](${suite.logDir}/console.log) |`,
  );
}

const summary = [
  '# Test execution summary',
  '',
  `Generated by \`npm run evidence\` on ${new Date().toISOString()} (Node ${process.version}, ${process.platform}).`,
  '',
  '| Suite | Command | Result | Scenarios | Steps | Reports |',
  '|---|---|---|---|---|---|',
  ...rows,
  '',
  'Other evidence:',
  '',
  '- UI screenshots for every scenario: [`ui/screenshots/`](ui/screenshots/)',
  '- SQL output tables and screenshots: [`sql/results.md`](sql/results.md), [`sql/screenshots/`](sql/screenshots/)',
  '- Self-healing reports: [`self-healing/healing-report.md`](self-healing/healing-report.md) (healing on), [`self-healing/healing-report-detect-only.md`](self-healing/healing-report-detect-only.md) (healing off)',
  '',
];
fs.writeFileSync(path.join(REPORTS, 'SUMMARY.md'), summary.join('\n'));
console.log(`\nSummary written to reports/SUMMARY.md`);
